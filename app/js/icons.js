// Returns the SVG code of an icon. "size" is the width in CSS pixels.
// The icon uses the current text color.
function pixelIcon(name, size) {
  const grid = ICON_GRIDS[name];
  const columns = grid[0].length;
  const rows = grid.length;
  const height = Math.round(size * rows / columns);

  let rects = "";
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < columns; x++) {
      if (grid[y][x] === "#") {
        rects = rects + '<rect x="' + x + '" y="' + y + '" width="1" height="1"/>';
      }
    }
  }

  return '<svg class="icon" width="' + size + '" height="' + height + '" ' +
    'viewBox="0 0 ' + columns + ' ' + rows + '" fill="currentColor" ' +
    'shape-rendering="crispEdges" aria-hidden="true">' + rects + '</svg>';
}
